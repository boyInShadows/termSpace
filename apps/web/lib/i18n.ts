export type Locale = "en" | "fa";

export function localePath(path: string, locale: Locale): string {
  const normalized = path.startsWith("/") ? path : `/${path}`;
  return locale === "fa"
    ? `/fa${normalized === "/" ? "" : normalized}`
    : normalized;
}

